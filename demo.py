"""Показ возможностей бота одной командой: /demo.

Продавать бота проще, когда владелец студии видит весь путь клиента за
минуту, не набирая ничего сам. Команда проводит по нему: вопрос — ответ по
прайсу — кнопка записи — карточка заявки, которую получает владелец, —
напоминание неответившему — отчёт за неделю.

Ответ на вопрос — настоящий, через модель и прайс: это самое убедительное
место, и подделывать его нельзя. Карточка заявки и отчёт — примеры с
пометкой, потому что в чужом чате настоящих заявок нет.

Включается DEMO_MODE=true в .env — на демо-боте. У ботов студий выключено.
"""
from __future__ import annotations

import asyncio

import config

# Вопрос, с которого начинается показ. Должен быть в прайсе демо-бота.
QUESTION = "у меня Camry, сколько выйдет керамика и полировка перед ней?"

INTRO = (
    "👋 Покажу за минуту, как бот работает с вашими клиентами.\n\n"
    "Представьте: вечер, администратор ушёл, а человек пишет в Telegram студии…"
)

CLIENT_ASKS = "💬 <i>Клиент пишет:</i>\n«{q}»"

AFTER_ANSWER = (
    "☝️ Это настоящий ответ, а не заготовка: бот сам определил класс машины, "
    "взял цены из прайса и сложил. Чего в прайсе нет — не выдумает, отправит "
    "к менеджеру.\n\n"
    "Под ответом — кнопка записи. Клиент нажимает, бот спрашивает имя, "
    "телефон и удобное время. А владельцу в этот момент приходит вот что:"
)

LEAD_EXAMPLE = (
    "🔔 <b>Заявка №14</b>  <i>(пример)</i>\n\n"
    "👤 Дмитрий — +7 900 123-45-67\n"
    "🚗 Toyota Camry 2019\n"
    "🕒 Удобно: суббота, после 12\n"
    "❓ Спрашивал: керамика и полировка\n\n"
    "Написать в Telegram (@dmitry)\n"
    "[ ✅ Взял в работу ]"
)

AFTER_LEAD = (
    "Заявка приходит за секунду в чат студии — с контактом и тем, о чём "
    "человек спрашивал. Кнопка «Взял в работу», чтобы двое не позвонили одному "
    "клиенту.\n\n"
    "А если человек спросил цену и пропал? Через три часа бот напишет ему сам "
    "— один раз, не ночью:"
)

NUDGE_EXAMPLE = "💬 <i>Клиенту через 3 часа:</i>\n«{nudge}»"

AFTER_NUDGE = (
    "Ещё бот понимает голосовые и видеокружки — можете отправить прямо сейчас, "
    "расшифрует и ответит. На фото машины объяснит, что точную цену скажет "
    "мастер на осмотре, и предложит записаться.\n\n"
    "И раз в неделю владелец получает отчёт. Вот как он выглядит:"
)

REPORT_EXAMPLE = (
    "📊 <b>Отчёт за 7 дн.</b>  <i>(пример)</i>\n\n"
    "👥 Написали: 23 человека, 61 вопрос\n"
    "   новых — 19, вернулись — 4\n"
    "📝 Заявок на осмотр: 6 (взяты в работу: 5)\n"
    "   → записался каждый 4-й, кто написал\n\n"
    "💬 О чём спрашивали чаще всего:\n"
    "   керамика — 18 · полировка — 11 · химчистка — 9\n\n"
    "⏰ Когда пишут:\n"
    "   в рабочее время — 41%, вечером — 38%, ночью — 21%\n"
    "   → 36 обращений пришло, когда администратор не на месте, — бот ответил сразу\n\n"
    "❓ Не смог ответить (нет в прайсе): 4\n"
    "   • «тонировка задних стёкол» ×3\n"
    "   • «оклейка фар»\n"
    "   → добавьте это в прайс — или ответ «не делаем»"
)

OUTRO = (
    "Последний блок — самое ценное: люди спрашивают то, чего нет в вашем "
    "прайсе, и вы об этом узнаёте.\n\n"
    "Всё это работает в вашем боте, под вашим именем, на вашем прайсе. "
    "Запуск — один день, неделя бесплатно.\n\n"
    "Попробуйте сами: спросите что-нибудь про услуги, отправьте голосовое "
    "или нажмите «Записаться» под ответом выше."
)


async def run(message, state, answer_question) -> None:
    """Провести показ. answer_question — обработчик обычного вопроса бота:
    ответ должен быть настоящим."""
    async def say(text: str, pause: float = 1.6) -> None:
        await message.answer(text, parse_mode="HTML")
        await asyncio.sleep(pause)

    await say(INTRO, 2.2)
    await say(CLIENT_ASKS.format(q=QUESTION), 1.2)
    await answer_question(message, state, query=QUESTION)
    await asyncio.sleep(2.5)
    await say(AFTER_ANSWER, 2.4)
    await say(LEAD_EXAMPLE, 2.6)
    await say(AFTER_LEAD, 2.4)
    await say(NUDGE_EXAMPLE.format(nudge=config.NUDGE_TEXT), 2.2)
    await say(AFTER_NUDGE, 2.4)
    await say(REPORT_EXAMPLE, 3.0)
    await say(OUTRO, 0)
