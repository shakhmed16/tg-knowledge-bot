# -*- coding: utf-8 -*-
"""Проверка детектора противоречий в прайсе.

    python test_audit.py

Важны обе стороны: поймать настоящее расхождение и не поднимать шум там,
где услуги разные, а цифры совпали случайно.
"""
from __future__ import annotations

import os
import sys

os.environ.setdefault("BOT_TOKEN", "x")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import audit

# (название теста, записи, ожидаем ли конфликт)
CASES = [
    (
        "та же услуга, разъехалась одна цена",
        [
            (1, "полировка", "Восстановительная полировка кузова: класс 1 — 13 000 ₽, "
                             "класс 2 — 18 000 ₽, класс 3 — 22 000 ₽."),
            (2, "керамика", "Нанесение керамики: класс 1 — 22 000 ₽. Перед керамикой "
                            "нужна восстановительная полировка: класс 1 — 12 000 ₽, "
                            "класс 2 — 18 000 ₽, класс 3 — 22 000 ₽."),
        ],
        True,
    ),
    (
        "та же услуга, цены совпадают",
        [
            (1, "полировка", "Восстановительная полировка кузова: класс 1 — 13 000 ₽, "
                             "класс 2 — 18 000 ₽."),
            (2, "керамика", "Керамика: класс 1 — 22 000 ₽. Нужна восстановительная "
                            "полировка кузова: класс 1 — 13 000 ₽, класс 2 — 18 000 ₽."),
        ],
        False,
    ),
    (
        "разные услуги, случайно общая цифра",
        [
            (1, "кожа", "Химчистка кожаных сидений: класс 1 — 1 400 ₽, класс 2 — "
                        "1 650 ₽, класс 3 — 1 900 ₽."),
            (2, "велюр", "Химчистка велюра сидений: класс 1 — 1 900 ₽, класс 2 — "
                         "2 200 ₽, класс 3 — 2 500 ₽."),
        ],
        False,
    ),
    (
        "разные услуги, ничего общего",
        [
            (1, "экспресс", "Экспресс-полировка кузова: класс 1 — 6 000 ₽."),
            (2, "восстановительная", "Восстановительная полировка кузова: класс 1 — 13 000 ₽."),
        ],
        False,
    ),
    (
        "одна услуга в трёх записях, одна отстала",
        [
            (1, "мойка", "Экспресс-мойка: класс 1 — 500 ₽, класс 2 — 600 ₽."),
            (2, "комплекс", "В комплекс входит экспресс-мойка: класс 1 — 500 ₽, "
                            "класс 2 — 600 ₽."),
            (3, "акция", "По акции экспресс-мойка: класс 1 — 450 ₽, класс 2 — 600 ₽."),
        ],
        True,
    ),
]

ok = True
for name, rows, expect in CASES:
    found = audit.find_conflicts(rows)
    good = bool(found) == expect
    ok = ok and good
    print(f"{'OK  ' if good else 'FAIL'} {name}: найдено {len(found)}, ожидали "
          f"{'конфликт' if expect else 'тишину'}")
    for c in found:
        ids = ", ".join(str(e[0]) for e in c["entries"])
        print(f"       «{c['name']}» в записях {ids}")

print("\nИтог:", "все прошли" if ok else "есть провалы")
sys.exit(0 if ok else 1)
